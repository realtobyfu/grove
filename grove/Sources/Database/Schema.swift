import CryptoKit
import Foundation
import SQLiteData

// The tables behind every model. The SQL that creates them is in
// `AppDatabase.swift`, frozen once shipped: see the rules there.

/// Namespace for the tables until the SwiftData models are gone.
enum DB {}

extension ItemType: QueryBindable {}
extension ItemStatus: QueryBindable {}
extension SmartRuleLogic: QueryBindable {}
extension TagCategory: QueryBindable {}
extension ConnectionType: QueryBindable {}
extension ConversationTrigger: QueryBindable {}
extension ChatRole: QueryBindable {}
extension NudgeType: QueryBindable {}
extension NudgeStatus: QueryBindable {}

extension DB {
    /// The sharing root. Keep this table free of foreign keys: SQLiteData can
    /// only share a record that has none.
    @Table("boards")
    struct Board: Hashable, Identifiable, Sendable {
        let id: UUID
        var title: String = ""
        var boardDescription: String?
        var icon: String?
        var color: String?
        var createdAt: Date = .now
        var sortOrder: Int = 0
        var isSmart: Bool = false
        var smartRuleLogic: SmartRuleLogic = .or
        /// Per-board nudge frequency in hours. 0 = use global default, -1 = disabled for this board.
        var nudgeFrequencyHours: Int = 0
        /// Manual item order. Empty means none has been set.
        @Column(as: [UUID].JSONRepresentation.self)
        var itemOrder: [UUID] = []
    }

    /// `boardID` is the item's only foreign key, which is what lets a shared
    /// board carry its items along with it.
    @Table("items")
    struct Item: Hashable, Identifiable, Sendable {
        let id: UUID
        var title: String = ""
        var type: ItemType = .note
        var status: ItemStatus = .inbox
        var sourceURL: String?
        var content: String?
        var engagementScore: Float = 0
        @Column(as: [String: String].JSONRepresentation.self)
        var metadata: [String: String] = [:]
        var createdAt: Date = .now
        var updatedAt: Date = .now
        /// Inbox defer queue ("Read Later").
        var readLaterUntil: Date?
        var lastResurfacedAt: Date?
        var resurfaceIntervalDays: Int = 7
        var resurfaceCount: Int = 0
        var lastEngagedAt: Date?
        var isResurfacingPaused: Bool = false
        var boardID: DB.Board.ID?
    }

    /// Up to ~275 KB each, so kept out of `items`: every list reads that table,
    /// and SQLiteData turns BLOB columns into CKAssets.
    @Table("itemThumbnails")
    struct ItemThumbnail: Hashable, Identifiable, Sendable {
        @Column(primaryKey: true)
        let itemID: DB.Item.ID
        var imageData: Data
        var id: DB.Item.ID { itemID }
    }

    @Table("tags")
    struct Tag: Hashable, Identifiable, Sendable {
        let id: UUID
        var name: String = ""
        var isAutoGenerated: Bool = false
        var confidence: Float?
        var category: TagCategory = .custom
        /// A plain ID, not a foreign key: SyncEngine refuses a table that
        /// references itself. A trigger clears this when the parent is deleted.
        var parentTagID: UUID?
        /// Number of items using this tag at last trend calculation.
        var previousItemCount: Int = 0
        /// When the trend was last computed.
        var trendCalculatedAt: Date?
    }

    /// Two foreign keys, so this stays out of a shared board. CloudKit sharing
    /// can't carry many-to-many links.
    @Table("itemTags")
    struct ItemTag: Hashable, Identifiable, Sendable {
        let id: UUID
        var itemID: DB.Item.ID
        var tagID: DB.Tag.ID
    }

    @Table("boardSmartRuleTags")
    struct BoardSmartRuleTag: Hashable, Identifiable, Sendable {
        let id: UUID
        var boardID: DB.Board.ID
        var tagID: DB.Tag.ID
    }

    @Table("connections")
    struct Connection: Hashable, Identifiable, Sendable {
        let id: UUID
        var sourceItemID: DB.Item.ID?
        var targetItemID: DB.Item.ID?
        var type: ConnectionType = .related
        var note: String?
        var isAutoGenerated: Bool = false
        var createdAt: Date = .now
    }

    /// Deprecated in favour of `ReflectionBlock`, kept so old rows survive.
    @Table("annotations")
    struct Annotation: Hashable, Identifiable, Sendable {
        let id: UUID
        var itemID: DB.Item.ID?
        var content: String = ""
        var highlight: String?
        var position: Int?
        var createdAt: Date = .now
    }

    @Table("reflectionBlocks")
    struct ReflectionBlock: Hashable, Identifiable, Sendable {
        let id: UUID
        var itemID: DB.Item.ID?
        /// Raw on purpose: rows from before the type set shrank hold values
        /// with no matching case, which `blockType` reads as `.keyInsight`.
        var blockTypeRaw: String = ReflectionBlockType.keyInsight.rawValue
        var content: String = ""
        var highlight: String?
        var position: Int = 0
        var videoTimestamp: Int?
        /// A plain ID so that this table keeps a single foreign key and can
        /// travel with a shared board. A trigger clears it when the conversation
        /// is deleted.
        var conversationID: UUID?
        var createdAt: Date = .now
    }

    /// Registered as a private table, so a shared board never carries its chats.
    @Table("conversations")
    struct Conversation: Hashable, Identifiable, Sendable {
        let id: UUID
        var title: String = ""
        var trigger: ConversationTrigger = .userInitiated
        var createdAt: Date = .now
        var updatedAt: Date = .now
        var isArchived: Bool = false
        var boardID: DB.Board.ID?
        @Column(as: [UUID].JSONRepresentation.self)
        var seedItemIDs: [UUID] = []
    }

    @Table("chatMessages")
    struct ChatMessage: Hashable, Identifiable, Sendable {
        let id: UUID
        var conversationID: DB.Conversation.ID?
        var role: ChatRole = .user
        var content: String = ""
        var position: Int = 0
        var createdAt: Date = .now
        @Column(as: [UUID].JSONRepresentation.self)
        var referencedItemIDs: [UUID] = []
        var toolCallName: String?
        var isHidden: Bool = false
    }

    @Table("nudges")
    struct Nudge: Hashable, Identifiable, Sendable {
        let id: UUID
        var type: NudgeType = .resurface
        var targetItemID: DB.Item.ID?
        @Column(as: [UUID]?.JSONRepresentation.self)
        var relatedItemIDs: [UUID]?
        var message: String = ""
        var status: NudgeStatus = .pending
        var scheduledFor: Date = .now
        var createdAt: Date = .now
    }

    @Table("feedSources")
    struct FeedSource: Hashable, Identifiable, Sendable {
        let id: UUID
        var feedURL: String = ""
        var domain: String = ""
        var title: String?
        var lastFetchedAt: Date?
        var isEnabled: Bool = false
        var isAutoDiscovered: Bool = false
        /// Whether the user has ever explicitly subscribed to this feed. Distinct
        /// from `isEnabled` (currently fetching) so toggling a subscription off
        /// keeps it in the Subscriptions list instead of teleporting it back to
        /// "Suggested from your library".
        var isUserSubscribed: Bool = false
        var errorCount: Int = 0
        var createdAt: Date = .now
    }

    /// Source references are identifiers rather than foreign keys: a deleted
    /// article must not erase the passage a person learned from.
    @Table("flashcards")
    struct Flashcard: Hashable, Identifiable, Sendable {
        let id: UUID
        var question: String = ""
        var answer: String = ""
        @Column(as: [String].JSONRepresentation.self)
        var hints: [String] = []
        var sourceItemID: UUID?
        var sourceReflectionID: UUID?
        var sourceTitle: String = "Your flashcard"
        var sourceQuote: String?
        var sourceURL: String?
        var sourceLocator: String?
        @Column(as: [UUID].JSONRepresentation.self)
        var boardIDs: [UUID] = []
        var revision: Int = 1
        /// Changes only with the question/answer/hints, not suspension or metadata.
        var revisionStartedAt: Date = .now
        var createdAt: Date = .now
        var updatedAt: Date = .now
        var isSuspended: Bool = false
        var dueAt: Date = .now
        /// Detects content changes even when a caller edits a card directly.
        var revisionFingerprint: String = ""
        /// A tombstone preserves review history and makes deletion merge safely.
        var deletedAt: Date?
    }

    /// Append-only learning evidence. Retries reuse `id`, so the primary key
    /// deduplicates the event.
    @Table("flashcardReviews")
    struct FlashcardReview: Hashable, Identifiable, Sendable {
        let id: UUID
        var cardID: UUID
        var cardRevision: Int = 1
        /// Independent edits can share the same numeric revision on two devices.
        /// Only evidence for the winning content fingerprint schedules that card.
        var cardFingerprint: String = ""
        var reviewedAt: Date = .now
        var ratingRaw: String = RecallRating.again.rawValue
        var usedHint: Bool = false
        var readSource: Bool = false
        var sessionID: UUID
    }

    /// Learning choices belong to the synced library. Notification delivery and
    /// transient window/session layout remain local to each device.
    @Table("learningPreferences")
    struct LearningPreferences: Hashable, Identifiable, Sendable {
        let id: UUID
        @Column(as: [UUID].JSONRepresentation.self)
        var focusBoardIDs: [UUID] = []
        var sessionMinutes: Int = 3
        var updatedAt: Date = .now
    }

    /// Board links past an item's first, kept from the many-to-many SwiftData
    /// model so the import loses nothing. Local only: not synced, nothing reads
    /// it yet, and it has no foreign keys so it can never block a delete. Rows
    /// are cleared by triggers when their item or board goes.
    @Table("extraBoardLinks")
    struct ExtraBoardLink: Hashable, Identifiable, Sendable {
        let id: UUID
        var itemID: UUID
        var boardID: UUID
    }
}

// MARK: - Deterministic IDs

extension UUID {
    /// A UUID derived from `parts`, the same on every device. Join rows use it
    /// so that importing on two devices converges instead of duplicating.
    init(derivedFrom parts: String...) {
        var bytes = Array(SHA256.hash(data: Data(parts.joined(separator: "|").utf8)).prefix(16))
        bytes[6] = (bytes[6] & 0x0F) | 0x50 // version 5 layout: name-based
        bytes[8] = (bytes[8] & 0x3F) | 0x80 // RFC 4122 variant
        self.init(uuid: (
            bytes[0], bytes[1], bytes[2], bytes[3], bytes[4], bytes[5], bytes[6], bytes[7],
            bytes[8], bytes[9], bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15]
        ))
    }

    fileprivate var key: String { uuidString.lowercased() }
}

extension DB.ItemTag {
    init(itemID: UUID, tagID: UUID) {
        self.init(id: UUID(derivedFrom: "itemTags", itemID.key, tagID.key), itemID: itemID, tagID: tagID)
    }
}

extension DB.BoardSmartRuleTag {
    init(boardID: UUID, tagID: UUID) {
        self.init(id: UUID(derivedFrom: "boardSmartRuleTags", boardID.key, tagID.key), boardID: boardID, tagID: tagID)
    }
}

extension DB.ExtraBoardLink {
    init(itemID: UUID, boardID: UUID) {
        self.init(id: UUID(derivedFrom: "extraBoardLinks", itemID.key, boardID.key), itemID: itemID, boardID: boardID)
    }
}
