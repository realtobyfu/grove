import SwiftUI

/// Compact row for inbox items showing title, source domain, thumbnail,
/// auto-tag chips (confirm/dismiss), and time since added.
struct MobileInboxCard: View {
    let item: Item
    var onConfirmTag: ((Tag) -> Void)?
    var onDismissTag: ((Tag) -> Void)?

    /// Width each tag action occupies inside the visual chip.
    private static let tagActionSlot: CGFloat = 14
    private static let tagChipTrailingPadding: CGFloat = 4
    /// How far the dismiss target runs past the chip's edge. Chips keep this
    /// clear so the target can't land on the next chip.
    private static let tagTargetOverhang =
        LayoutDimensions.minTouchTarget - tagActionSlot - tagChipTrailingPadding

    private var isFetchingMetadata: Bool {
        item.isFetchingMetadata
    }

    var body: some View {
        HStack(spacing: Spacing.md) {
            // Thumbnail
            if let thumbnailData = item.thumbnail {
                thumbnailImage(thumbnailData)
                    .resizable()
                    .aspectRatio(contentMode: .fill)
                    .frame(width: 56, height: 56)
                    .clipShape(RoundedRectangle(cornerRadius: 8))
            }

            VStack(alignment: .leading, spacing: Spacing.xs) {
                // Title
                Text(item.title)
                    .font(.groveItemTitle)
                    .foregroundStyle(Color.textPrimary)
                    .lineLimit(2)

                // Source domain
                if let sourceURL = item.sourceURL,
                   let host = URL(string: sourceURL)?.host(percentEncoded: false) {
                    Text(host)
                        .font(.groveMeta)
                        .foregroundStyle(Color.textTertiary)
                        .lineLimit(1)
                }

                if isFetchingMetadata {
                    HStack(spacing: 4) {
                        ProgressView()
                            .controlSize(.small)
                        Text("Fetching metadata…")
                            .font(.groveMeta)
                            .foregroundStyle(Color.textMuted)
                    }
                } else if let summary = item.summary, !summary.isEmpty {
                    Text(summary)
                        .font(.groveBodySecondary)
                        .foregroundStyle(Color.textSecondary)
                        .lineLimit(2)
                } else if let preview = item.previewText {
                    Text(preview)
                        .font(.groveBodySecondary)
                        .foregroundStyle(Color.textSecondary)
                        .lineLimit(2)
                }

                // Auto-tag chips
                if !autoTags.isEmpty {
                    FlowLayout(spacing: 0) {
                        ForEach(autoTags) { tag in
                            autoTagChip(tag)
                        }
                    }
                }
            }

            Spacer(minLength: 0)

            // Time since added
            Text(compactRelativeTime(from: item.createdAt))
                .font(.groveMeta)
                .foregroundStyle(Color.textMuted)
                .lineLimit(1)
        }
        .padding(.vertical, Spacing.xs)
        #if os(iOS)
        .hoverEffect(.highlight)
        #endif
    }

    // MARK: - Helpers

    private var autoTags: [Tag] {
        item.tags.filter { $0.isAutoGenerated }
    }

    private func autoTagChip(_ tag: Tag) -> some View {
        HStack(spacing: 0) {
            Text(tag.name)
                .font(.groveTag)
                .foregroundStyle(Color.textPrimary)
                .lineLimit(1)
                .fixedSize()
                .padding(.trailing, Spacing.xs)

            if let onConfirmTag {
                tagAction(
                    "checkmark",
                    label: "Confirm tag \(tag.name)",
                    color: Color.textSecondary,
                    alignment: .trailing
                ) {
                    onConfirmTag(tag)
                }
            }

            if let onDismissTag {
                tagAction(
                    "xmark",
                    label: "Dismiss tag \(tag.name)",
                    color: Color.textMuted,
                    alignment: .leading
                ) {
                    onDismissTag(tag)
                }
            }
        }
        .padding(.leading, 8)
        .padding(.trailing, Self.tagChipTrailingPadding)
        .padding(.vertical, 4)
        // A background rather than a clip, so the 44pt targets stay whole.
        .background(Color.bgCard, in: RoundedRectangle(cornerRadius: 4))
        .overlay(
            RoundedRectangle(cornerRadius: 4)
                .stroke(Color.borderTag, lineWidth: 1)
        )
        .padding(.trailing, Self.tagTargetOverhang)
        .frame(minHeight: LayoutDimensions.minTouchTarget)
    }

    /// A glyph-sized action with a 44pt target that overflows the chip.
    /// `alignment` pins the glyph to one side of the target, so confirm reaches
    /// left over the tag name, dismiss reaches right, and the two never overlap.
    private func tagAction(
        _ systemImage: String,
        label: String,
        color: Color,
        alignment: Alignment,
        action: @escaping () -> Void
    ) -> some View {
        Button(action: action) {
            Image(systemName: systemImage)
                .font(.system(size: 10, weight: .bold))
                .foregroundStyle(color)
                .frame(width: Self.tagActionSlot)
                .frame(
                    width: LayoutDimensions.minTouchTarget,
                    height: LayoutDimensions.minTouchTarget,
                    alignment: alignment
                )
                .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .frame(width: Self.tagActionSlot, height: Self.tagActionSlot, alignment: alignment)
        .accessibilityLabel(label)
    }

    private func thumbnailImage(_ data: Data) -> Image {
        #if os(iOS)
        if let uiImage = UIImage(data: data) {
            return Image(uiImage: uiImage)
        }
        #else
        if let nsImage = NSImage(data: data) {
            return Image(nsImage: nsImage)
        }
        #endif
        return Image(systemName: "photo")
    }

    private func compactRelativeTime(from date: Date) -> String {
        let elapsed = max(0, Int(Date.now.timeIntervalSince(date)))

        if elapsed < 3600 {
            let minutes = max(1, elapsed / 60)
            return "\(minutes)m"
        }

        if elapsed < 86_400 {
            let hours = elapsed / 3600
            return "\(hours)h"
        }

        if elapsed < 604_800 {
            let days = elapsed / 86_400
            return "\(days)d"
        }

        if elapsed < 2_592_000 {
            let weeks = elapsed / 604_800
            return "\(weeks)w"
        }

        if elapsed < 31_536_000 {
            let months = elapsed / 2_592_000
            return "\(months)mo"
        }

        let years = elapsed / 31_536_000
        return "\(years)y"
    }
}
