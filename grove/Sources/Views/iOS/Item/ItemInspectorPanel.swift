import SwiftUI
import SwiftData

/// An item's info, opened from the iOS reader's Info action: a sheet with
/// detents on iPhone, a popover from the toolbar on iPad.
///
/// Holds what the item is (title, source, dates), what it is connected to
/// (its own connections, with the add-connection flow, and the backlinks
/// other items point here with), the boards it is filed in, and the summary
/// and tags capture wrote for it. The iOS counterpart of the macOS
/// `InspectorPanelView`.
struct ItemInspectorPanel: View {
    @Bindable var item: Item
    /// Opens a connected item. When nil, connection rows are plain text.
    var onOpenItem: ((Item) -> Void)? = nil

    @Environment(\.modelContext) private var modelContext
    @Environment(\.dismiss) private var dismiss
    @Query(sort: \Board.sortOrder) private var allBoards: [Board]

    @State private var showBoardPicker = false
    @State private var showConnectionPicker = false
    @State private var isEnrichingItem = false
    @State private var isSuggestingTags = false

    /// Extract a display domain from the item's sourceURL string.
    private var sourceDomain: String? {
        guard let urlString = item.sourceURL,
              let url = URL(string: urlString),
              let host = url.host(percentEncoded: false) else {
            return nil
        }
        // Strip leading "www." for cleaner display
        if host.hasPrefix("www.") {
            return String(host.dropFirst(4))
        }
        return host
    }

    private var isFetchingMetadata: Bool {
        item.isFetchingMetadata
    }

    private var canRunMetadataEnrichment: Bool {
        item.type == .article && (item.sourceURL?.isEmpty == false)
    }

    private var suggestedTags: [Tag] {
        item.tags.filter { $0.isAutoGenerated }
    }

    /// The item's own connections, newest first: a to-many relationship has
    /// no inherent order, and an arbitrary one would reshuffle between opens.
    private var outgoingConnections: [Connection] {
        item.outgoingConnections.sorted { $0.createdAt > $1.createdAt }
    }

    /// Connections other items made to this one, newest first.
    private var backlinks: [Connection] {
        item.incomingConnections.sorted { $0.createdAt > $1.createdAt }
    }

    var body: some View {
        NavigationStack {
            ScrollView {
                VStack(alignment: .leading, spacing: Spacing.xl) {
                    headerSection
                    metadataSection

                    Divider()
                    connectionsSection

                    Divider()
                    backlinksSection

                    Divider()
                    boardsSection

                    Divider()
                    summarySection

                    if item.type == .article {
                        Divider()
                        discussionSuggestionsToggle
                    }
                }
                .padding(.horizontal, LayoutDimensions.inspectorPaddingH)
                .padding(.top, Spacing.sm)
                .padding(.bottom, LayoutDimensions.inspectorPaddingTop)
            }
            .background(Color.bgInspector)
            .navigationTitle("Info")
            #if os(iOS)
            .navigationBarTitleDisplayMode(.inline)
            #endif
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button {
                        dismiss()
                    } label: {
                        Image(systemName: "xmark")
                            .font(.system(size: 14, weight: .medium))
                            .foregroundStyle(Color.textSecondary)
                    }
                    .accessibilityLabel("Close")
                }
            }
        }
        .sheet(isPresented: $showBoardPicker) {
            boardPickerSheet
        }
        .sheet(isPresented: $showConnectionPicker) {
            AddConnectionSheet(item: item) { target, type in
                connect(to: target, as: type)
            }
        }
    }

    // MARK: - Header

    private var headerSection: some View {
        VStack(alignment: .leading, spacing: Spacing.sm) {
            HStack(spacing: Spacing.sm) {
                Image(systemName: item.type.iconName)
                    .foregroundStyle(Color.textSecondary)
                Text(item.type.displayName)
                    .font(.groveMeta)
                    .foregroundStyle(Color.textSecondary)
            }

            Text(item.title)
                .font(.groveItemTitle)
                .foregroundStyle(Color.textPrimary)

            if let url = item.sourceURL, !url.isEmpty {
                HStack(spacing: Spacing.xs) {
                    Image(systemName: "link")
                        .font(.system(size: 12, weight: .medium))
                    Text(url)
                        .lineLimit(1)
                        .truncationMode(.middle)
                }
                .font(.groveMeta)
                .foregroundStyle(Color.textMuted)
            }
        }
    }

    // MARK: - Metadata

    private var metadataSection: some View {
        VStack(alignment: .leading, spacing: Spacing.sm) {
            metadataRow(
                icon: "calendar",
                label: "Created",
                value: item.createdAt.formatted(date: .abbreviated, time: .shortened)
            )
            metadataRow(
                icon: "calendar.badge.clock",
                label: "Updated",
                value: item.updatedAt.formatted(date: .abbreviated, time: .shortened)
            )
            if let domain = sourceDomain {
                metadataRow(icon: "globe", label: "Source", value: domain)
            }
        }
    }

    private func metadataRow(icon: String, label: String, value: String) -> some View {
        HStack(spacing: Spacing.sm) {
            Image(systemName: icon)
                .font(.system(size: 12, weight: .medium))
                .foregroundStyle(Color.textMuted)
                .frame(width: 16)
            Text(label)
                .font(.groveMeta)
                .foregroundStyle(Color.textMuted)
            Spacer()
            Text(value)
                .font(.groveMeta)
                .foregroundStyle(Color.textSecondary)
                .lineLimit(1)
        }
    }

    // MARK: - Connections

    private var connectionsSection: some View {
        VStack(alignment: .leading, spacing: Spacing.xs) {
            sectionHeader("Connections") {
                Button {
                    showConnectionPicker = true
                } label: {
                    Image(systemName: "plus.circle")
                        .font(.system(size: 15, weight: .medium))
                        .foregroundStyle(Color.textSecondary)
                        .frame(width: LayoutDimensions.minTouchTarget,
                               height: LayoutDimensions.minTouchTarget)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .accessibilityLabel("Add connection")
                .accessibilityHint("Choose an item in your library to connect this one to.")
            }

            let outgoing = outgoingConnections
            if outgoing.isEmpty {
                Text("No connections yet")
                    .font(.groveBodySecondary)
                    .foregroundStyle(Color.textMuted)
            } else {
                ForEach(outgoing) { connection in
                    connectionRow(connection, isOutgoing: true)
                }
            }
        }
    }

    /// Every kind of incoming link on equal footing: connections made by hand
    /// from the other item, in chat, and the "Linked From" trails recorded
    /// when this page was reached by reading another item.
    private var backlinksSection: some View {
        VStack(alignment: .leading, spacing: Spacing.xs) {
            sectionHeader("Backlinks") { EmptyView() }

            let incoming = backlinks
            if incoming.isEmpty {
                Text("No items link here yet")
                    .font(.groveBodySecondary)
                    .foregroundStyle(Color.textMuted)
            } else {
                ForEach(incoming) { connection in
                    connectionRow(connection, isOutgoing: false)
                }
            }
        }
    }

    private func connectionRow(_ connection: Connection, isOutgoing: Bool) -> some View {
        let linkedItem = isOutgoing ? connection.targetItem : connection.sourceItem
        let linkedTitle = linkedItem?.title ?? "Unknown"

        return HStack(spacing: 0) {
            if let onOpenItem, let linkedItem {
                Button {
                    onOpenItem(linkedItem)
                } label: {
                    connectionLabel(connection, title: linkedTitle, isOutgoing: isOutgoing)
                }
                .buttonStyle(.plain)
                .accessibilityHint(isOutgoing ? "Opens the connected item." : "Opens the item that links here.")
            } else {
                connectionLabel(connection, title: linkedTitle, isOutgoing: isOutgoing)
            }

            Button {
                deleteConnection(connection)
            } label: {
                Image(systemName: "xmark")
                    .font(.system(size: 11, weight: .medium))
                    .foregroundStyle(Color.textTertiary)
                    .frame(width: LayoutDimensions.minTouchTarget,
                           height: LayoutDimensions.minTouchTarget)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .accessibilityLabel("Remove connection to \(linkedTitle)")
        }
        .contextMenu {
            if let onOpenItem, let linkedItem {
                Button("Open", systemImage: "arrow.up.right") { onOpenItem(linkedItem) }
            }
            Button("Remove Connection", systemImage: "xmark", role: .destructive) {
                deleteConnection(connection)
            }
        }
    }

    private func connectionLabel(_ connection: Connection, title: String, isOutgoing: Bool) -> some View {
        HStack(alignment: .top, spacing: Spacing.sm) {
            Image(systemName: isOutgoing ? "arrow.right" : "arrow.left")
                .font(.system(size: 12, weight: .medium))
                .foregroundStyle(Color.textSecondary)
                .frame(width: 16)
                .padding(.top, 3)

            VStack(alignment: .leading, spacing: 3) {
                Text(title)
                    .font(.groveBodySecondary)
                    .foregroundStyle(Color.textPrimary)
                    .lineLimit(2)
                    .multilineTextAlignment(.leading)

                Text(connection.type.displayLabel(isOutgoing: isOutgoing))
                    .font(.groveBadge)
                    .foregroundStyle(Color.textTertiary)
                    .padding(.horizontal, Spacing.xsm)
                    .padding(.vertical, 2)
                    .background(Color.accentBadge)
                    .clipShape(RoundedRectangle(cornerRadius: Radius.tag))
            }

            Spacer(minLength: 0)
        }
        .padding(.vertical, Spacing.xs)
        .frame(minHeight: LayoutDimensions.minTouchTarget)
        .contentShape(Rectangle())
    }

    private func connect(to target: Item, as type: ConnectionType) {
        // Writing a connection keeps both ends: createConnection promotes a
        // feed suggestion on either side into the library.
        _ = ItemViewModel(modelContext: modelContext)
            .createConnection(source: item, target: target, type: type)
    }

    private func deleteConnection(_ connection: Connection) {
        ItemViewModel(modelContext: modelContext).deleteConnection(connection)
    }

    // MARK: - Boards

    private var boardsSection: some View {
        VStack(alignment: .leading, spacing: Spacing.xs) {
            sectionHeader("Boards") {
                Button {
                    showBoardPicker = true
                } label: {
                    Image(systemName: "plus.circle")
                        .font(.system(size: 15, weight: .medium))
                        .foregroundStyle(Color.textSecondary)
                        .frame(width: LayoutDimensions.minTouchTarget,
                               height: LayoutDimensions.minTouchTarget)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .accessibilityLabel("Add to board")
            }

            if item.boards.isEmpty {
                Text("Not in any board")
                    .font(.groveBodySecondary)
                    .foregroundStyle(Color.textMuted)
            } else {
                ForEach(item.boards) { board in
                    HStack(spacing: Spacing.sm) {
                        Image(systemName: board.icon ?? "folder")
                            .font(.system(size: 12, weight: .medium))
                            .foregroundStyle(Color.textSecondary)
                            .frame(width: 16)
                        Text(board.title)
                            .font(.groveBody)
                            .foregroundStyle(Color.textPrimary)
                    }
                    .padding(.vertical, Spacing.xs)
                }
            }
        }
    }

    /// The shared board picker: it offers only boards an item can be filed
    /// into, and can create one by name.
    private var boardPickerSheet: some View {
        let decision = BoardSuggestionMetadata.decision(from: item)
        return BoardPickerView(
            boards: allBoards,
            mode: .add,
            suggestedName: decision?.suggestedName ?? "",
            recommendedBoardID: decision?.recommendedBoardID,
            alternativeBoardIDs: decision?.alternativeBoardIDs ?? [],
            onSelect: { board in
                BoardSuggestionMetadata.clearPendingSuggestion(on: item)
                ItemViewModel(modelContext: modelContext).assignToBoard(item, board: board)
            },
            onCreate: { title in
                createAndAssignBoard(named: title)
            }
        )
    }

    private func createAndAssignBoard(named rawTitle: String) {
        let title = BoardSuggestionEngine.cleanedBoardName(rawTitle)
        guard !title.isEmpty else { return }

        let itemViewModel = ItemViewModel(modelContext: modelContext)
        if let existing = allBoards.first(where: {
            $0.title.localizedCaseInsensitiveCompare(title) == .orderedSame
        }) {
            BoardSuggestionMetadata.clearPendingSuggestion(on: item)
            itemViewModel.assignToBoard(item, board: existing)
        } else {
            let board = Board(title: title)
            board.sortOrder = (allBoards.map(\.sortOrder).max() ?? -1) + 1
            modelContext.insert(board)
            BoardSuggestionMetadata.clearPendingSuggestion(on: item)
            itemViewModel.assignToBoard(item, board: board)
        }
    }

    // MARK: - Summary + Tags

    private var summarySection: some View {
        VStack(alignment: .leading, spacing: Spacing.md) {
            VStack(alignment: .leading, spacing: Spacing.xs) {
                sectionHeader("Summary") {
                    if canRunMetadataEnrichment {
                        Button {
                            Task { await runEnrichmentPipeline() }
                        } label: {
                            Group {
                                if isEnrichingItem {
                                    ProgressView()
                                        .controlSize(.small)
                                } else {
                                    Label("Refresh", systemImage: "arrow.clockwise")
                                        .font(.groveMeta)
                                        .foregroundStyle(Color.textSecondary)
                                }
                            }
                            .frame(minHeight: LayoutDimensions.minTouchTarget)
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                        .disabled(isEnrichingItem || isSuggestingTags)
                        .accessibilityLabel("Refresh metadata and summary")
                    }
                }

                if isFetchingMetadata || isEnrichingItem {
                    HStack(spacing: Spacing.sm) {
                        ProgressView()
                            .controlSize(.small)
                        Text("Fetching metadata and summary…")
                            .font(.groveMeta)
                            .foregroundStyle(Color.textSecondary)
                    }
                }

                if let summary = item.summary, !summary.isEmpty {
                    Text(summary)
                        .font(.groveBodySecondary)
                        .foregroundStyle(Color.textSecondary)
                        .fixedSize(horizontal: false, vertical: true)
                } else {
                    Text("No summary yet.")
                        .font(.groveBodySecondary)
                        .foregroundStyle(Color.textMuted)
                }
            }

            VStack(alignment: .leading, spacing: Spacing.xs) {
                sectionHeader("Tags") {
                    Button {
                        suggestTags()
                    } label: {
                        Group {
                            if isSuggestingTags {
                                ProgressView()
                                    .controlSize(.small)
                            } else {
                                Text("Suggest")
                                    .font(.groveMeta)
                                    .foregroundStyle(Color.textSecondary)
                            }
                        }
                        .frame(minHeight: LayoutDimensions.minTouchTarget)
                        .contentShape(Rectangle())
                    }
                    .buttonStyle(.plain)
                    .disabled(isSuggestingTags || isEnrichingItem)
                    .accessibilityLabel("Suggest tags for this item")
                }

                if !item.tags.isEmpty {
                    FlowLayout(spacing: Spacing.xs) {
                        ForEach(item.tags.prefix(8)) { tag in
                            if tag.isAutoGenerated {
                                TagChip(tag: tag, mode: .autoTag(
                                    onConfirm: { confirmTag(tag) },
                                    onDismiss: { dismissTag(tag) }
                                ))
                            } else {
                                TagChip(tag: tag, mode: .display)
                            }
                        }
                    }
                } else {
                    Text("No tags yet.")
                        .font(.groveBodySecondary)
                        .foregroundStyle(Color.textMuted)
                }

                if !suggestedTags.isEmpty {
                    Text("Confirm suggested tags with the checkmark, or remove them with x.")
                        .font(.groveMeta)
                        .foregroundStyle(Color.textTertiary)
                        .padding(.top, Spacing.xs)
                }
            }
        }
    }

    // MARK: - Discussion suggestions

    private var discussionSuggestionsToggle: some View {
        Button {
            item.isIncludedInDiscussionSuggestions.toggle()
            item.updatedAt = .now
            try? modelContext.save()
        } label: {
            HStack(spacing: Spacing.sm) {
                Image(systemName: item.isIncludedInDiscussionSuggestions ? "checkmark.circle.fill" : "circle")
                    .font(.system(size: 14, weight: .medium))
                    .foregroundStyle(item.isIncludedInDiscussionSuggestions ? Color.textPrimary : Color.textTertiary)
                Text("Include in discussion suggestions")
                    .font(.groveBody)
                    .foregroundStyle(item.isIncludedInDiscussionSuggestions ? Color.textPrimary : Color.textSecondary)
            }
            .frame(minHeight: LayoutDimensions.minTouchTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
    }

    // MARK: - Section header

    private func sectionHeader<Accessory: View>(
        _ title: String,
        @ViewBuilder accessory: () -> Accessory
    ) -> some View {
        HStack(spacing: Spacing.sm) {
            Text(title)
                .sectionHeaderStyle()
                .accessibilityAddTraits(.isHeader)
            Spacer(minLength: Spacing.sm)
            accessory()
        }
        .frame(minHeight: LayoutDimensions.minTouchTarget)
    }

    // MARK: - Enrichment Actions

    /// Runs only when asked (the Refresh button). Opening Info never fetches
    /// or spends an AI request by itself.
    private func runEnrichmentPipeline() async {
        guard !isEnrichingItem else { return }
        guard let sourceURL = item.sourceURL, !sourceURL.isEmpty else { return }

        isEnrichingItem = true
        item.isFetchingMetadata = true
        try? modelContext.save()

        let itemID = item.id
        let fallbackTitle = item.title
        let enricher = ItemMetadataEnricher()
        let tagger = ItemAutoTagger()

        let metadata = await enricher.enrichURLItem(
            itemID: itemID,
            urlString: sourceURL,
            context: modelContext,
            overwrite: .refresh
        )

        await tagger.autoTagItem(itemID: itemID, context: modelContext)
        enricher.markSummaryReviewIfNeeded(itemID: itemID, context: modelContext)

        if item.type == .article {
            await enricher.generateOverview(
                itemID: itemID,
                context: modelContext,
                title: metadata.title ?? fallbackTitle,
                description: metadata.description,
                bodyText: metadata.bodyText
            )
            enricher.extractSummaryFallback(itemID: itemID, context: modelContext)
            enricher.markSummaryReviewIfNeeded(itemID: itemID, context: modelContext)
        }

        isEnrichingItem = false
    }

    private func suggestTags() {
        guard !isSuggestingTags else { return }
        isSuggestingTags = true
        let itemID = item.id

        Task {
            let tagger = ItemAutoTagger()
            await tagger.autoTagItem(itemID: itemID, context: modelContext)
            isSuggestingTags = false
        }
    }

    private func confirmTag(_ tag: Tag) {
        tag.isAutoGenerated = false
        item.updatedAt = .now
        try? modelContext.save()
    }

    private func dismissTag(_ tag: Tag) {
        item.tags.removeAll { $0.id == tag.id }
        item.updatedAt = .now
        try? modelContext.save()
    }
}

// MARK: - Connection candidates

/// Which items the add-connection picker offers for an item: anything else
/// in the library that isn't already connected to it in either direction.
/// Dismissed items and feed suggestions the user never kept stay out.
enum ConnectionCandidates {
    static func filter(
        _ items: [Item],
        for item: Item,
        query: String,
        limit: Int = 60
    ) -> [Item] {
        let connectedIDs = Set(
            item.outgoingConnections.compactMap(\.targetItem?.id)
                + item.incomingConnections.compactMap(\.sourceItem?.id)
        )
        let trimmedQuery = query.trimmingCharacters(in: .whitespacesAndNewlines)
        return Array(
            items.lazy
                .filter { candidate in
                    candidate.id != item.id
                        && !connectedIDs.contains(candidate.id)
                        && candidate.status != .dismissed
                        && !candidate.isFeedSuggestion
                        && (trimmedQuery.isEmpty || candidate.title.localizedStandardContains(trimmedQuery))
                }
                .prefix(limit)
        )
    }
}

// MARK: - Add connection

/// Picks the item to connect to and how the two relate. Choosing an item
/// writes the connection and closes the sheet.
private struct AddConnectionSheet: View {
    let item: Item
    let onConnect: (Item, ConnectionType) -> Void

    @Environment(\.dismiss) private var dismiss
    @Query(sort: \Item.updatedAt, order: .reverse) private var allItems: [Item]
    @State private var query = ""
    @State private var connectionType: ConnectionType = .related

    private var candidates: [Item] {
        ConnectionCandidates.filter(allItems, for: item, query: query)
    }

    var body: some View {
        NavigationStack {
            List {
                Section {
                    Picker("Relationship", selection: $connectionType) {
                        ForEach(ConnectionType.userSelectableCases, id: \.self) { type in
                            Text(type.displayLabel).tag(type)
                        }
                    }
                    .pickerStyle(.menu)
                    .font(.groveBody)
                }

                Section {
                    if candidates.isEmpty {
                        Text(query.isEmpty ? "Nothing else in your library to connect yet." : "No matching items")
                            .font(.groveBodySecondary)
                            .foregroundStyle(Color.textMuted)
                    } else {
                        ForEach(candidates) { candidate in
                            Button {
                                onConnect(candidate, connectionType)
                                dismiss()
                            } label: {
                                candidateRow(candidate)
                            }
                            .buttonStyle(.plain)
                        }
                    }
                } header: {
                    Text(query.isEmpty ? "Recent" : "Matches")
                        .sectionHeaderStyle()
                }
            }
            #if os(iOS)
            .listStyle(.insetGrouped)
            #endif
            .scrollContentBackground(.hidden)
            .background(Color.bgInspector)
            .searchable(text: $query, prompt: "Search your library")
            .navigationTitle("Add Connection")
            #if os(iOS)
            .navigationBarTitleDisplayMode(.inline)
            #endif
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel") { dismiss() }
                        .font(.groveBody)
                }
            }
        }
        .tint(Color.textPrimary)
        #if os(iOS)
        .presentationDetents([.large])
        .presentationDragIndicator(.visible)
        #endif
    }

    private func candidateRow(_ candidate: Item) -> some View {
        HStack(alignment: .top, spacing: Spacing.sm) {
            Image(systemName: candidate.type.iconName)
                .font(.system(size: 13, weight: .medium))
                .foregroundStyle(Color.textSecondary)
                .frame(width: 18)
                .padding(.top, 2)

            VStack(alignment: .leading, spacing: 2) {
                Text(candidate.title)
                    .font(.groveBody)
                    .foregroundStyle(Color.textPrimary)
                    .lineLimit(2)
                if let board = candidate.boards.first {
                    Text(board.title)
                        .font(.groveMeta)
                        .foregroundStyle(Color.textTertiary)
                        .lineLimit(1)
                }
            }

            Spacer(minLength: 0)
        }
        .frame(minHeight: LayoutDimensions.minTouchTarget)
        .contentShape(Rectangle())
        .accessibilityElement(children: .combine)
        .accessibilityHint("Connects \(item.title) to this item.")
    }
}
