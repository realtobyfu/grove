import SwiftUI

/// Compact list row for items on iOS — title, source domain,
/// optional thumbnail. Minimum 44pt height for touch targets.
struct MobileItemCardView: View {
    let item: Item

    @ScaledMetric(relativeTo: .headline) private var thumbnailSize: CGFloat = 48

    private var suggestedTags: [Tag] {
        item.tags.filter { $0.isAutoGenerated }
    }

    var body: some View {
        HStack(alignment: .top, spacing: Spacing.md) {
            // Thumbnail (if available), top-aligned with the title
            if let thumbnailData = item.thumbnail {
                thumbnailImage(thumbnailData)
                    .resizable()
                    .aspectRatio(contentMode: .fill)
                    .frame(width: thumbnailSize, height: thumbnailSize)
                    .clipShape(RoundedRectangle(cornerRadius: Radius.control))
            }

            VStack(alignment: .leading, spacing: Spacing.xs) {
                // Title
                Text(item.title)
                    .font(.groveListTitle)
                    .foregroundStyle(Color.textPrimary)
                    .lineLimit(2)

                HStack(spacing: Spacing.sm) {
                    // Board indicator
                    Text(item.boards.first?.title ?? "Unfiled")
                        .font(.groveMeta)
                        .foregroundStyle(Color.textTertiary)

                    // Source domain
                    if let sourceURL = item.sourceURL,
                       let host = URL(string: sourceURL)?.host(percentEncoded: false) {
                        Text("·")
                            .font(.groveMeta)
                            .foregroundStyle(Color.textTertiary)
                        Text(host)
                            .font(.groveMeta)
                            .foregroundStyle(Color.textMuted)
                            .lineLimit(1)
                    }
                }

                if let summary = item.summary, !summary.isEmpty {
                    Text(summary)
                        .font(.groveBodySecondary)
                        .foregroundStyle(Color.textSecondary)
                        .lineLimit(2)
                }

                // Tags: one mono meta line, truncated at the tail
                if !suggestedTags.isEmpty {
                    Text(suggestedTags.map(\.name).joined(separator: " · "))
                        .font(.groveMeta)
                        .foregroundStyle(Color.textMuted)
                        .lineLimit(1)
                        .truncationMode(.tail)
                }
            }

            Spacer(minLength: 0)
        }
        .frame(minHeight: LayoutDimensions.minTouchTarget)
        .padding(.vertical, Spacing.xs)
        // Every row's separator starts at the content inset, thumbnail or not.
        .alignmentGuide(.listRowSeparatorLeading) { dimensions in
            dimensions[.leading]
        }
        #if os(iOS)
        .hoverEffect(.highlight)
        .draggable(item.dragURL)
        #endif
    }

    // MARK: - Helpers

    private func thumbnailImage(_ data: Data) -> Image {
        #if os(iOS)
        if let uiImage = UIImage(data: data) {
            return Image(uiImage: uiImage)
        }
        #else
        if let nsImage = NSImage(data: data) {
            return Image(nsImage: nsImage)
        }
        #endif
        return Image(systemName: "photo")
    }
}
