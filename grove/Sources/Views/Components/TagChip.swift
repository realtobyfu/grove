import SwiftUI

/// Unified tag chip component with multiple display modes.
/// Replaces duplicated tag chip rendering in InboxCard, ItemCardView, and ContentView.
struct TagChip: View {
    let tag: Tag
    var mode: Mode = .display
    /// `.autoTag` only: give confirm and dismiss full 44pt touch targets that
    /// overflow the drawn chip (iPhone inbox rows). The chip keeps clear space
    /// on its trailing side so the dismiss target can't land on the next chip.
    var largeTargets: Bool = false

    enum Mode {
        /// Read-only, solid border
        case display
        /// Dashed border + confirm/dismiss buttons (inbox auto-tags)
        case autoTag(onConfirm: (() -> Void)?, onDismiss: (() -> Void)?)
        /// Solid border + close button (removable)
        case removable(onRemove: () -> Void)
        /// Borderless filled chip for source cards and list rows.
        /// (Name kept for callers; the shape is the tag radius, not a capsule.)
        case capsule
    }

    /// Width each tag action occupies inside the drawn chip (large targets).
    private static let actionSlot: CGFloat = 14
    private static let largeTrailingPadding = Spacing.xs
    /// How far the dismiss target runs past the chip's trailing edge.
    private static let targetOverhang =
        LayoutDimensions.minTouchTarget - actionSlot - largeTrailingPadding

    var body: some View {
        switch mode {
        case .display:
            displayChip
        case .autoTag(let onConfirm, let onDismiss):
            autoTagChip(onConfirm: onConfirm, onDismiss: onDismiss)
        case .removable(let onRemove):
            removableChip(onRemove: onRemove)
        case .capsule:
            capsuleChip
        }
    }

    private var tagBorderStyle: StrokeStyle {
        tag.isAutoGenerated
            ? StrokeStyle(lineWidth: 1, dash: [3, 2])
            : StrokeStyle(lineWidth: 1)
    }

    // MARK: - Display

    private var displayChip: some View {
        Text(tag.name)
            .font(.groveTag)
            .foregroundStyle(tag.isAutoGenerated ? Color.textSecondary : Color.textPrimary)
            .padding(.horizontal, Spacing.sm)
            .padding(.vertical, 3)
            .background(Color.bgCard, in: RoundedRectangle(cornerRadius: Radius.tag))
            .overlay(
                RoundedRectangle(cornerRadius: Radius.tag)
                    .strokeBorder(style: tagBorderStyle)
                    .foregroundStyle(tag.isAutoGenerated ? Color.borderTagDashed : Color.borderTag)
            )
    }

    // MARK: - Auto Tag

    private func autoTagChip(onConfirm: (() -> Void)?, onDismiss: (() -> Void)?) -> some View {
        HStack(spacing: largeTargets ? 0 : 3) {
            Text(tag.name)
                .font(.groveTag)
                .foregroundStyle(tag.isAutoGenerated ? Color.textSecondary : Color.textPrimary)
                .lineLimit(1)
                .fixedSize()
                .padding(.trailing, largeTargets ? Spacing.xs : 0)

            if tag.isAutoGenerated {
                if let onConfirm {
                    tagAction(
                        "checkmark",
                        label: "Confirm tag \(tag.name)",
                        help: "Confirm tag",
                        color: Color.textSecondary,
                        alignment: .trailing,
                        action: onConfirm
                    )
                }
                if let onDismiss {
                    tagAction(
                        "xmark",
                        label: "Dismiss tag \(tag.name)",
                        help: "Remove tag",
                        color: Color.textTertiary,
                        alignment: .leading,
                        action: onDismiss
                    )
                }
            }
        }
        .padding(.leading, Spacing.sm)
        .padding(.trailing, largeTargets ? Self.largeTrailingPadding : Spacing.sm)
        .padding(.vertical, 3)
        // A background rather than a clip, so large targets stay whole.
        .background(Color.bgCard, in: RoundedRectangle(cornerRadius: Radius.tag))
        .overlay(
            RoundedRectangle(cornerRadius: Radius.tag)
                .strokeBorder(style: tagBorderStyle)
                .foregroundStyle(tag.isAutoGenerated ? Color.borderTagDashed : Color.borderTag)
        )
        .padding(.trailing, largeTargets ? Self.targetOverhang : 0)
        .frame(minHeight: largeTargets ? LayoutDimensions.minTouchTarget : nil)
    }

    /// A glyph-sized action. With `largeTargets` it gets a 44pt target that
    /// overflows the chip; `alignment` pins the glyph to one side of that
    /// target, so confirm reaches left over the tag name, dismiss reaches
    /// right, and the two never overlap.
    @ViewBuilder
    private func tagAction(
        _ systemImage: String,
        label: String,
        help: String,
        color: Color,
        alignment: Alignment,
        action: @escaping () -> Void
    ) -> some View {
        if largeTargets {
            Button(action: action) {
                Image(systemName: systemImage)
                    .font(.system(size: 10, weight: .bold))
                    .foregroundStyle(color)
                    .frame(width: Self.actionSlot)
                    .frame(
                        width: LayoutDimensions.minTouchTarget,
                        height: LayoutDimensions.minTouchTarget,
                        alignment: alignment
                    )
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .frame(width: Self.actionSlot, height: Self.actionSlot, alignment: alignment)
            .accessibilityLabel(label)
        } else {
            Button(action: action) {
                Image(systemName: systemImage)
                    .font(.system(size: 8, weight: .bold))
                    .foregroundStyle(color)
            }
            .buttonStyle(.plain)
            .help(help)
            .accessibilityLabel(label)
        }
    }

    // MARK: - Removable

    private func removableChip(onRemove: @escaping () -> Void) -> some View {
        HStack(spacing: 3) {
            Text(tag.name)
                .font(.groveTag)
                .foregroundStyle(Color.textPrimary)
            Button {
                onRemove()
            } label: {
                Image(systemName: "xmark")
                    .font(.system(size: 7, weight: .bold))
                    .foregroundStyle(Color.textTertiary)
            }
            .buttonStyle(.plain)
        }
        .padding(.horizontal, Spacing.sm)
        .padding(.vertical, 3)
        .background(Color.bgCard, in: RoundedRectangle(cornerRadius: Radius.tag))
        .overlay(
            RoundedRectangle(cornerRadius: Radius.tag)
                .stroke(tag.isAutoGenerated ? Color.borderTagDashed : Color.borderTag, lineWidth: 1)
        )
    }

    // MARK: - Capsule

    private var capsuleChip: some View {
        Text(tag.name)
            .font(.groveTag)
            .foregroundStyle(tag.isAutoGenerated ? Color.textSecondary : Color.textPrimary)
            .padding(.horizontal, Spacing.sm)
            .padding(.vertical, 3)
            .background(Color.bgInput, in: RoundedRectangle(cornerRadius: Radius.tag))
    }
}
