import Foundation
import SQLiteData

enum ConnectionType: String, Codable, CaseIterable, QueryBindable {
    case related
    case contradicts
    case buildsOn
    case inspiredBy
    case sameTopic
    /// Provenance: the target page was reached by following a link while
    /// reading the source item. Recorded automatically, never picked by hand.
    case linkedFrom

    var displayLabel: String {
        switch self {
        case .related: "Related"
        case .contradicts: "Contradicts"
        case .buildsOn: "Builds On"
        case .inspiredBy: "Inspired By"
        case .sameTopic: "Same Topic"
        case .linkedFrom: "Linked From"
        }
    }

    /// The label as read from one end of the edge. `.linkedFrom` is the only
    /// asymmetric type: on the page you were reading it points forward ("Links
    /// To" the article you opened), and only on the destination does "Linked
    /// From" describe what happened. Every other type reads the same either way.
    func displayLabel(isOutgoing: Bool) -> String {
        switch self {
        case .linkedFrom: isOutgoing ? "Links To" : "Linked From"
        default: displayLabel
        }
    }

    /// Types a person can choose when creating a connection by hand.
    /// `.linkedFrom` is earned by browsing, so offering it in a picker would
    /// let the user assert a provenance that never happened.
    static var userSelectableCases: [ConnectionType] {
        allCases.filter { $0 != .linkedFrom }
    }
}

@Table("connections")
struct Connection: Hashable, Identifiable, Sendable {
    let id: UUID
    var sourceItemID: Item.ID?
    var targetItemID: Item.ID?
    var type: ConnectionType = .related
    var note: String?
    var isAutoGenerated: Bool = false
    var createdAt: Date = .now
}

extension Connection {
    init(sourceItemID: Item.ID, targetItemID: Item.ID, type: ConnectionType) {
        self.init(id: UUID(), sourceItemID: sourceItemID, targetItemID: targetItemID, type: type)
    }
}

