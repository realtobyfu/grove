import Foundation
import SwiftUI
import SQLiteData

enum TagCategory: String, Codable, CaseIterable, QueryBindable {
    case topic
    case concept
    case technology
    case person
    case custom

    var displayName: String {
        switch self {
        case .topic: return "Topics"
        case .concept: return "Concepts"
        case .technology: return "Technology"
        case .person: return "People"
        case .custom: return "Custom"
        }
    }

    var iconName: String {
        switch self {
        case .topic: return "text.book.closed"
        case .concept: return "lightbulb"
        case .technology: return "hammer"
        case .person: return "person"
        case .custom: return "tag"
        }
    }

    var color: Color {
        .textSecondary
    }
}

/// Trend direction for tag usage over time
enum TagTrend: String, Codable {
    case increasing
    case stable
    case decreasing
}

@Table("tags")
struct Tag: Hashable, Identifiable, Sendable {
    let id: UUID
    var name: String = ""
    var isAutoGenerated: Bool = false
    var confidence: Float?
    var category: TagCategory = .custom
    /// A plain ID, not a foreign key: SyncEngine refuses a table that
    /// references itself. A trigger clears this when the parent is deleted.
    var parentTagID: UUID?
    /// Number of items using this tag at last trend calculation.
    var previousItemCount: Int = 0
    /// When the trend was last computed.
    var trendCalculatedAt: Date?
}

extension Tag {
    init(name: String, category: TagCategory = .custom, isAutoGenerated: Bool = false, confidence: Float? = nil) {
        self.init(id: UUID(), name: name, isAutoGenerated: isAutoGenerated, confidence: confidence, category: category)
    }
}
