import Foundation
import SwiftData

/// The SwiftData models, kept only so `LegacyStoreImporter` can read an old store.
///
/// Nothing else may use these. They hold no behaviour, only what a store needs
/// to open: stored properties, relationships, and the accessors the importer
/// reads. `SchemaMigrationTests` pins their entity hashes, so a change here that
/// alters a stored property fails there. Nesting in this enum does not change the
/// entity names.
enum Legacy {
    // CloudKit requires every relationship to be optional and to declare an
    // inverse, so the stored properties are optional arrays, and each is fronted
    // by a non-optional accessor.
    //
    // Pre-2.0 stores used the plain names (`items`, ...). Don't map them with
    // `originalName`: a rename in the model blocks every migration of a synced
    // store. `LegacyStoreMigration` carries pre-2.0 stores across instead.

    @Model
    final class Item {
        var id: UUID = UUID()
        var title: String = ""
        var type: ItemType = ItemType.note
        var status: ItemStatus = ItemStatus.inbox
        var sourceURL: String?
        var content: String?
        var thumbnail: Data?
        var engagementScore: Float = 0
        var metadata: [String: String] = [:]
        var createdAt: Date = Date.now
        var updatedAt: Date = Date.now
        var readLaterUntil: Date?
        var lastResurfacedAt: Date?
        var resurfaceIntervalDays: Int = 7
        var resurfaceCount: Int = 0
        var lastEngagedAt: Date?
        var isResurfacingPaused: Bool = false

        @Relationship(inverse: \Board.itemsStorage)
        var boardsStorage: [Board]? = []
        @Relationship(inverse: \Tag.itemsStorage)
        var tagsStorage: [Tag]? = []
        @Relationship(deleteRule: .cascade, inverse: \Annotation.item)
        var annotationsStorage: [Annotation]? = []
        @Relationship(deleteRule: .cascade, inverse: \ReflectionBlock.item)
        var reflectionsStorage: [ReflectionBlock]? = []
        @Relationship(deleteRule: .cascade, inverse: \Connection.sourceItem)
        var outgoingConnectionsStorage: [Connection]? = []
        @Relationship(deleteRule: .cascade, inverse: \Connection.targetItem)
        var incomingConnectionsStorage: [Connection]? = []
        @Relationship(deleteRule: .cascade, inverse: \Nudge.targetItem)
        var nudgesStorage: [Nudge]? = []

        var boards: [Board] {
            get { boardsStorage ?? [] }
            set { boardsStorage = newValue }
        }

        var tags: [Tag] {
            get { tagsStorage ?? [] }
            set { tagsStorage = newValue }
        }

        init(title: String, type: ItemType) {
            self.id = UUID()
            self.title = title
            self.type = type
        }
    }

    @Model
    final class Board {
        var id: UUID = UUID()
        var title: String = ""
        var boardDescription: String?
        var icon: String?
        var color: String?
        var createdAt: Date = Date.now
        var sortOrder: Int = 0
        var isSmart: Bool = false
        var smartRuleLogic: SmartRuleLogic = SmartRuleLogic.or
        var nudgeFrequencyHours: Int = 0
        var itemOrderData: Data?

        var itemsStorage: [Item]? = []
        var smartRuleTagsStorage: [Tag]? = []
        @Relationship(inverse: \Conversation.board) var conversationsStorage: [Conversation]? = []

        var smartRuleTags: [Tag] {
            get { smartRuleTagsStorage ?? [] }
            set { smartRuleTagsStorage = newValue }
        }

        init(title: String, icon: String? = nil, color: String? = nil) {
            self.id = UUID()
            self.title = title
            self.icon = icon
            self.color = color
        }
    }

    @Model
    final class Tag {
        var id: UUID = UUID()
        var name: String = ""
        var isAutoGenerated: Bool = false
        var confidence: Float?
        var category: TagCategory = TagCategory.custom

        @Relationship(inverse: \Tag.childTagsStorage) var parentTag: Tag?
        var childTagsStorage: [Tag]? = []

        var itemsStorage: [Item]? = []
        @Relationship(inverse: \Board.smartRuleTagsStorage)
        var smartRuleBoardsStorage: [Board]? = []

        var previousItemCount: Int = 0
        var trendCalculatedAt: Date?

        init(name: String, category: TagCategory = .custom, isAutoGenerated: Bool = false, confidence: Float? = nil) {
            self.id = UUID()
            self.name = name
            self.isAutoGenerated = isAutoGenerated
            self.confidence = confidence
            self.category = category
        }
    }

    @Model
    final class Connection {
        var id: UUID = UUID()
        var sourceItem: Item?
        var targetItem: Item?
        var type: ConnectionType = ConnectionType.related
        var note: String?
        var isAutoGenerated: Bool = false
        var createdAt: Date = Date.now

        init(sourceItem: Item, targetItem: Item, type: ConnectionType) {
            self.id = UUID()
            self.sourceItem = sourceItem
            self.targetItem = targetItem
            self.type = type
        }
    }

    @Model
    final class Annotation {
        var id: UUID = UUID()
        var item: Item?
        var content: String = ""
        var highlight: String?
        var position: Int?
        var createdAt: Date = Date.now

        init(item: Item, content: String, highlight: String? = nil, position: Int? = nil) {
            self.id = UUID()
            self.item = item
            self.content = content
            self.highlight = highlight
            self.position = position
        }
    }

    @Model
    final class ReflectionBlock {
        var id: UUID = UUID()
        var item: Item?
        var blockTypeRaw: String = ReflectionBlockType.keyInsight.rawValue
        var content: String = ""
        var highlight: String?
        var position: Int = 0
        var videoTimestamp: Int?
        var conversation: Conversation?
        var createdAt: Date = Date.now

        init(item: Item, blockType: ReflectionBlockType, content: String = "", highlight: String? = nil, position: Int = 0, videoTimestamp: Int? = nil) {
            self.id = UUID()
            self.item = item
            self.blockTypeRaw = blockType.rawValue
            self.content = content
            self.highlight = highlight
            self.position = position
            self.videoTimestamp = videoTimestamp
        }
    }

    @Model
    final class Conversation {
        var id: UUID = UUID()
        var title: String = ""
        var trigger: ConversationTrigger = ConversationTrigger.userInitiated
        var createdAt: Date = Date.now
        var updatedAt: Date = Date.now
        var isArchived: Bool = false
        var board: Board?

        @Relationship(deleteRule: .cascade, inverse: \ChatMessage.conversation)
        var messagesStorage: [ChatMessage]? = []
        @Relationship(inverse: \ReflectionBlock.conversation)
        var createdReflectionsStorage: [ReflectionBlock]? = []

        var seedItemIDs: [UUID] = []

        init(
            title: String = "New Conversation",
            trigger: ConversationTrigger = .userInitiated,
            board: Board? = nil,
            seedItemIDs: [UUID] = []
        ) {
            self.id = UUID()
            self.title = title
            self.trigger = trigger
            self.board = board
            self.seedItemIDs = seedItemIDs
        }
    }

    @Model
    final class ChatMessage {
        var id: UUID = UUID()
        var conversation: Conversation?
        var role: ChatRole = ChatRole.user
        var content: String = ""
        var position: Int = 0
        var createdAt: Date = Date.now
        var referencedItemIDs: [UUID] = []
        var toolCallName: String?
        var isHidden: Bool = false

        init(
            role: ChatRole,
            content: String,
            position: Int,
            isHidden: Bool = false,
            toolCallName: String? = nil,
            referencedItemIDs: [UUID] = []
        ) {
            self.id = UUID()
            self.role = role
            self.content = content
            self.position = position
            self.referencedItemIDs = referencedItemIDs
            self.toolCallName = toolCallName
            self.isHidden = isHidden
        }
    }

    @Model
    final class Nudge {
        var id: UUID = UUID()
        var type: NudgeType = NudgeType.resurface
        var targetItem: Item?
        var relatedItemIDs: [UUID]?
        var message: String = ""
        var status: NudgeStatus = NudgeStatus.pending
        var scheduledFor: Date = Date.now
        var createdAt: Date = Date.now

        init(type: NudgeType, message: String, scheduledFor: Date = .now, targetItem: Item? = nil) {
            self.id = UUID()
            self.type = type
            self.targetItem = targetItem
            self.message = message
            self.scheduledFor = scheduledFor
        }
    }

    @Model
    final class FeedSource {
        var id: UUID = UUID()
        var feedURL: String = ""
        var domain: String = ""
        var title: String?
        var lastFetchedAt: Date?
        var isEnabled: Bool = false
        var isAutoDiscovered: Bool = false
        var isUserSubscribed: Bool = false
        var errorCount: Int = 0
        var createdAt: Date = Date.now

        init(
            feedURL: String,
            domain: String,
            title: String? = nil,
            isAutoDiscovered: Bool = true,
            isEnabled: Bool = true,
            isUserSubscribed: Bool = false
        ) {
            self.id = UUID()
            self.feedURL = feedURL
            self.domain = domain
            self.title = title
            self.isEnabled = isEnabled
            self.isAutoDiscovered = isAutoDiscovered
            self.isUserSubscribed = isUserSubscribed
        }
    }

    // The learning models are `User…` because a new entity's class name has to
    // sort after every 2.0 entity. Read "Migration Limits" in
    // SharedModelContainer.swift.

    @Model
    final class UserFlashcard {
        var id: UUID = UUID()
        var question: String = ""
        var answer: String = ""
        var hints: [String] = []
        var sourceItemID: UUID?
        var sourceReflectionID: UUID?
        var sourceTitle: String = "Your flashcard"
        var sourceQuote: String?
        var sourceURL: String?
        var sourceLocator: String?
        var boardIDs: [UUID] = []
        var revision: Int = 1
        var revisionStartedAt: Date = Date.now
        var createdAt: Date = Date.now
        var updatedAt: Date = Date.now
        var isSuspended: Bool = false
        var dueAt: Date = Date.now
        var revisionFingerprint: String = ""
        var deletedAt: Date?

        init(question: String, answer: String, hints: [String] = []) {
            self.question = question
            self.answer = answer
            self.hints = hints
        }
    }

    @Model
    final class UserFlashcardReview {
        var id: UUID = UUID()
        var cardID: UUID = UUID()
        var cardRevision: Int = 1
        var cardFingerprint: String = ""
        var reviewedAt: Date = Date.now
        var ratingRaw: String = RecallRating.again.rawValue
        var usedHint: Bool = false
        var readSource: Bool = false
        var sessionID: UUID = UUID()

        init(cardID: UUID, cardRevision: Int, rating: RecallRating, sessionID: UUID) {
            self.cardID = cardID
            self.cardRevision = cardRevision
            self.ratingRaw = rating.rawValue
            self.sessionID = sessionID
        }
    }

    @Model
    final class UserLearningPreferences {
        var id: UUID = UUID(uuidString: "2776BFF0-9131-4BA7-9F43-9809986417D1")!
        var focusBoardIDs: [UUID] = []
        var sessionMinutes: Int = 3
        var updatedAt: Date = Date.now

        init(focusBoardIDs: [UUID] = [], sessionMinutes: Int = 3) {
            self.focusBoardIDs = focusBoardIDs
            self.sessionMinutes = sessionMinutes
        }
    }
}
