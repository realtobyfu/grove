import Foundation
import SwiftData
import Testing
@testable import grove

/// The add-connection flow behind the iOS Info panel: what the picker offers
/// and what writing a connection does to both ends.
@MainActor
struct ItemConnectionTests {
    @Test func creatingAConnectionUpdatesBothItems() throws {
        let context = try makeContext()
        let source = insertItem("Source", in: context)
        let target = insertItem("Target", in: context)

        let connection = try #require(
            ItemViewModel(modelContext: context).createConnection(source: source, target: target, type: .buildsOn)
        )

        #expect(source.outgoingConnections.map(\.id) == [connection.id])
        #expect(target.incomingConnections.map(\.id) == [connection.id])
        #expect(source.incomingConnections.isEmpty)
        #expect(target.outgoingConnections.isEmpty)
        #expect(connection.type == .buildsOn)
        #expect(!connection.isAutoGenerated)
    }

    @Test func connectingKeepsAFeedSuggestionOnEitherEnd() throws {
        let context = try makeContext()
        let source = insertItem("Issue", in: context)
        let target = insertItem("Other issue", in: context)
        for item in [source, target] {
            item.isFeedSuggestion = true
            #expect(item.isFeedSuggestion)
        }

        _ = ItemViewModel(modelContext: context).createConnection(source: source, target: target, type: .related)

        for item in [source, target] {
            #expect(!item.isFeedSuggestion)
            #expect(item.status == .active)
            #expect(item.isFeedIssueRead)
        }
    }

    @Test func anItemCannotConnectToItself() throws {
        let context = try makeContext()
        let item = insertItem("Alone", in: context)

        let connection = ItemViewModel(modelContext: context).createConnection(source: item, target: item, type: .related)

        #expect(connection == nil)
        #expect(item.outgoingConnections.isEmpty)
        #expect(item.incomingConnections.isEmpty)
    }

    @Test func removingAConnectionClearsBothItems() throws {
        let context = try makeContext()
        let viewModel = ItemViewModel(modelContext: context)
        let source = insertItem("Source", in: context)
        let target = insertItem("Target", in: context)
        let connection = try #require(viewModel.createConnection(source: source, target: target, type: .related))

        viewModel.deleteConnection(connection)

        #expect(source.outgoingConnections.isEmpty)
        #expect(target.incomingConnections.isEmpty)
    }

    @Test func candidatesLeaveOutTheItemAndWhatIsAlreadyConnected() throws {
        let context = try makeContext()
        let viewModel = ItemViewModel(modelContext: context)
        let item = insertItem("Item", in: context)
        let linkedTo = insertItem("Linked to", in: context)
        let linksHere = insertItem("Links here", in: context)
        let free = insertItem("Free", in: context)
        _ = viewModel.createConnection(source: item, target: linkedTo, type: .related)
        _ = viewModel.createConnection(source: linksHere, target: item, type: .inspiredBy)

        let candidates = ConnectionCandidates.filter([item, linkedTo, linksHere, free], for: item, query: "")

        #expect(candidates.map(\.id) == [free.id])
    }

    @Test func candidatesLeaveOutDismissedItemsAndUnkeptSuggestions() throws {
        let context = try makeContext()
        let item = insertItem("Item", in: context)
        let dismissed = insertItem("Dismissed", in: context)
        dismissed.status = .dismissed
        let suggestion = insertItem("Suggestion", in: context)
        suggestion.isFeedSuggestion = true
        let archived = insertItem("Archived", in: context)
        archived.status = .archived

        let candidates = ConnectionCandidates.filter([dismissed, suggestion, archived], for: item, query: "")

        #expect(candidates.map(\.id) == [archived.id])
    }

    @Test func candidatesMatchTheQueryAndKeepTheirOrder() throws {
        let context = try makeContext()
        let item = insertItem("Item", in: context)
        let first = insertItem("Zettelkasten method", in: context)
        let other = insertItem("Spaced repetition", in: context)
        let second = insertItem("The zettelkasten", in: context)
        let items = [first, other, second]

        let matches = ConnectionCandidates.filter(items, for: item, query: "  zettel ")

        #expect(matches.map(\.id) == [first.id, second.id])
        #expect(ConnectionCandidates.filter(items, for: item, query: "", limit: 2).map(\.id) == [first.id, other.id])
    }

    private func insertItem(_ title: String, in context: ModelContext) -> Item {
        let item = Item(title: title, type: .note)
        context.insert(item)
        return item
    }

    private func makeContext() throws -> ModelContext {
        let schema = SharedModelContainer.schema
        let config = ModelConfiguration("ItemConnectionTests", schema: schema, isStoredInMemoryOnly: true, cloudKitDatabase: .none)
        let container = try ModelContainer(for: schema, configurations: [config])
        return ModelContext(container)
    }
}
