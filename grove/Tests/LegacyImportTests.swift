/// Every fixture here is synthetic and lives in a temporary folder.
struct LegacyImportTests {
    private let folder: URL

    init() throws {
        folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("LegacyImportTests-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
    }

    private var source: URL { folder.appendingPathComponent("Grove.store") }
    private var destination: URL { folder.appendingPathComponent("library/grove.sqlite") }

    /// Runs `body` against a new on-disk SwiftData store, which is then closed.
    private func withStore(_ body: (ModelContext) throws -> Void) throws {
        let configuration = ModelConfiguration(
            "Grove",
            schema: SharedModelContainer.schema,
            url: source,
            cloudKitDatabase: .none
        )
        let container = try ModelContainer(for: SharedModelContainer.schema, configurations: [configuration])
        let context = ModelContext(container)
        try body(context)
        try context.save()
    }

    private func read<T>(_ body: (Database) throws -> T) throws -> T {
        let queue = try DatabaseQueue(path: destination.path(percentEncoded: false))
        defer { try? queue.close() }
        return try queue.read(body)
    }

    private func hash(of url: URL) throws -> String {
        SHA256.hash(data: try Data(contentsOf: url)).map { String(format: "%02x", $0) }.joined()
    }

    @Test func carriesEveryModelAcrossWithItsIDs() throws {
        var itemID = UUID()
        var boardID = UUID()
        var conversationID = UUID()
        try withStore { context in
            let board = Board(title: "Reading", icon: "book")
            board.sortOrder = 3
            board.setManualOrder([])
            let item = Item(title: "Essay", type: .article)
            item.status = .active
            item.sourceURL = "https://example.com/essay"
            item.content = "Body"
            item.metadata = ["format": "pdf"]
            item.thumbnail = Data([1, 2, 3])
            let other = Item(title: "Note", type: .note)
            let tag = Tag(name: "swift", category: .technology, isAutoGenerated: true, confidence: 0.5)
            let parent = Tag(name: "languages")
            tag.parentTag = parent
            let connection = Connection(sourceItem: item, targetItem: other, type: .buildsOn)
            connection.note = "follows from"
            let conversation = Conversation(title: "Chat", trigger: .knowledgeGap, board: board, seedItemIDs: [item.id])
            let message = ChatMessage(role: .assistant, content: "Hello", position: 2, referencedItemIDs: [item.id])
            message.conversation = conversation
            let block = ReflectionBlock(item: item, blockType: .connection, content: "Thought", position: 4, videoTimestamp: 9)
            block.conversation = conversation
            let nudge = Nudge(type: .resurface, message: "Revisit", targetItem: item)
            nudge.relatedItemIDs = [other.id]
            let source = FeedSource(feedURL: "https://example.com/feed", domain: "example.com", title: "Feed")
            let card = Flashcard(question: "Q", answer: "A", sourceItem: item, hints: ["hint"])
            let review = FlashcardReview(cardID: card.id, cardRevision: 1, rating: .good, sessionID: UUID())
            let preferences = LearningPreferences(focusBoardIDs: [board.id], sessionMinutes: 5)

            for model in [board, item, other, tag, parent, connection, conversation, message, block, nudge, source, card, review, preferences] as [any PersistentModel] {
                context.insert(model)
            }
            item.boards = [board]
            item.tags = [tag]
            board.smartRuleTags = [tag]
            itemID = item.id
            boardID = board.id
            conversationID = conversation.id
        }

        let report = try LegacyStoreImporter.run(source: source, destination: destination)
        #expect(report.duplicatesDropped.isEmpty)
        #expect(report.rowCounts["items"] == 2)

        try read { db throws in
            let item = try #require(try DB.Item.find(itemID).fetchOne(db))
            #expect(item.title == "Essay")
            #expect(item.type == .article)
            #expect(item.status == .active)
            #expect(item.metadata == ["format": "pdf"])
            #expect(item.boardID == boardID)
            #expect(try DB.ItemThumbnail.find(itemID).fetchOne(db)?.imageData == Data([1, 2, 3]))

            let tag = try #require(try DB.Tag.where { $0.name.eq("swift") }.fetchOne(db))
            #expect(tag.category == .technology)
            #expect(tag.confidence == 0.5)
            #expect(try DB.Tag.find(try #require(tag.parentTagID)).fetchOne(db)?.name == "languages")
            #expect(try DB.ItemTag.all.fetchAll(db) == [DB.ItemTag(itemID: itemID, tagID: tag.id)])
            #expect(try DB.BoardSmartRuleTag.all.fetchAll(db) == [DB.BoardSmartRuleTag(boardID: boardID, tagID: tag.id)])

            let connection = try #require(try DB.Connection.all.fetchOne(db))
            #expect(connection.type == .buildsOn)
            #expect(connection.sourceItemID == itemID)
            #expect(connection.note == "follows from")

            let conversation = try #require(try DB.Conversation.find(conversationID).fetchOne(db))
            #expect(conversation.boardID == boardID)
            #expect(conversation.trigger == .knowledgeGap)
            #expect(conversation.seedItemIDs == [itemID])

            let message = try #require(try DB.ChatMessage.all.fetchOne(db))
            #expect(message.conversationID == conversationID)
            #expect(message.referencedItemIDs == [itemID])

            let block = try #require(try DB.ReflectionBlock.all.fetchOne(db))
            #expect(block.conversationID == conversationID)
            #expect(block.itemID == itemID)
            #expect(block.videoTimestamp == 9)

            #expect(try DB.Nudge.all.fetchOne(db)?.targetItemID == itemID)
            #expect(try DB.FeedSource.all.fetchOne(db)?.domain == "example.com")
            #expect(try DB.Flashcard.all.fetchOne(db)?.hints == ["hint"])
            #expect(try DB.FlashcardReview.all.fetchOne(db)?.ratingRaw == "good")
            #expect(try DB.LearningPreferences.all.fetchOne(db)?.focusBoardIDs == [boardID])
        }
    }

    @Test func multiBoardItemKeepsItsFirstBoardAndHoldsTheRest() throws {
        var itemID = UUID()
        var firstID = UUID()
        var extraIDs: Set<UUID> = []
        try withStore { context in
            let first = Board(title: "First")
            first.sortOrder = 1
            let second = Board(title: "Second")
            second.sortOrder = 2
            let third = Board(title: "Third")
            third.sortOrder = 3
            let item = Item(title: "Everywhere", type: .note)
            for model in [third, first, second, item] as [any PersistentModel] { context.insert(model) }
            item.boards = [third, first, second]
            itemID = item.id
            firstID = first.id
            extraIDs = [second.id, third.id]
        }

        try LegacyStoreImporter.run(source: source, destination: destination)

        try read { db throws in
            #expect(try DB.Item.find(itemID).fetchOne(db)?.boardID == firstID)
            let links = try DB.ExtraBoardLink.all.fetchAll(db)
            #expect(links.count == 2)
            #expect(Set(links.map(\.boardID)) == extraIDs)
            #expect(Set(links.map(\.itemID)) == [itemID])
        }
    }

    @Test func joinRowIDsDependOnlyOnThePair() throws {
        let item = UUID()
        let tag = UUID()
        #expect(DB.ItemTag(itemID: item, tagID: tag).id == DB.ItemTag(itemID: item, tagID: tag).id)
        #expect(DB.ItemTag(itemID: item, tagID: UUID()).id != DB.ItemTag(itemID: item, tagID: tag).id)
        // The same pair in another table must not collide.
        #expect(DB.ItemTag(itemID: item, tagID: tag).id != DB.BoardSmartRuleTag(boardID: item, tagID: tag).id)
        // Pinned: the ID must never change between builds, or two devices diverge.
        let pinned = try #require(UUID(uuidString: "00000000-0000-0000-0000-000000000001"))
        let other = try #require(UUID(uuidString: "00000000-0000-0000-0000-000000000002"))
        #expect(DB.ItemTag(itemID: pinned, tagID: other).id.uuidString == "902AEC4F-7217-5E9D-9790-F33E678DDF3A")
    }

    @Test func importingTwiceProducesTheSameIDs() throws {
        try withStore { context in
            let item = Item(title: "Tagged", type: .note)
            let tag = Tag(name: "shared")
            context.insert(item)
            context.insert(tag)
            item.tags = [tag]
        }
        let otherDestination = folder.appendingPathComponent("other/grove.sqlite")
        try LegacyStoreImporter.run(source: source, destination: destination)
        try LegacyStoreImporter.run(source: source, destination: otherDestination)

        let first = try read { try DB.ItemTag.all.fetchAll($0) }
        let queue = try DatabaseQueue(path: otherDestination.path(percentEncoded: false))
        defer { try? queue.close() }
        #expect(first == (try queue.read { try DB.ItemTag.all.fetchAll($0) }))
    }

    @Test func rowsRepeatingAnIDCollapseToOne() throws {
        let sharedID = UUID()
        try withStore { context in
            for _ in 0..<2 {
                let nudge = Nudge(type: .resurface, message: "Same row twice")
                nudge.id = sharedID
                context.insert(nudge)
            }
            context.insert(Nudge(type: .staleInbox, message: "Different row"))
        }

        let report = try LegacyStoreImporter.run(source: source, destination: destination)

        #expect(report.duplicatesDropped == ["nudges": 1])
        #expect(try read { try DB.Nudge.all.fetchCount($0) } == 2)
    }

    @Test func aFailedImportLeavesNoDatabaseAndTheSourceUntouched() throws {
        try Data("not a store".utf8).write(to: source)
        let before = try hash(of: source)

        #expect(throws: (any Error).self) {
            try LegacyStoreImporter.run(source: source, destination: destination)
        }

        #expect(!FileManager.default.fileExists(atPath: destination.path(percentEncoded: false)))
        #expect(try hash(of: source) == before)
        let leftovers = try FileManager.default.contentsOfDirectory(atPath: destination.deletingLastPathComponent().path(percentEncoded: false))
        #expect(leftovers.isEmpty)
    }

    @Test func aSuccessfulImportLeavesTheSourceUntouched() throws {
        try withStore { context in
            context.insert(Item(title: "Kept", type: .note))
        }
        let before = try hash(of: source)

        try LegacyStoreImporter.run(source: source, destination: destination)

        #expect(try hash(of: source) == before)
    }

    @Test func verifyRejectsAMissingRow() throws {
        try withStore { context in
            context.insert(Item(title: "One", type: .note))
            context.insert(Item(title: "Two", type: .note))
        }
        var snapshot = try LegacySnapshot(storeAt: source)
        let staged = folder.appendingPathComponent("staged.sqlite")
        let dropped = snapshot.items.removeLast()
        try LegacyStoreImporter.write(snapshot, to: staged)

        snapshot.items.append(dropped)
        #expect(throws: LegacyStoreImporter.ImportError.self) {
            try LegacyStoreImporter.verify(staged, against: snapshot)
        }
    }

    @Test func verifyRejectsASnapshotThatLostRowsFromTheStore() throws {
        try withStore { context in
            context.insert(Item(title: "One", type: .note))
            context.insert(Item(title: "Two", type: .note))
        }
        var snapshot = try LegacySnapshot(storeAt: source)
        snapshot.items.removeLast()
        let staged = folder.appendingPathComponent("staged.sqlite")
        try LegacyStoreImporter.write(snapshot, to: staged)

        #expect(throws: LegacyStoreImporter.ImportError.self) {
            try LegacyStoreImporter.verify(staged, against: snapshot)
        }
    }
}

/// The schema has to stay inside what SQLiteData can sync and share.
struct DatabaseSchemaTests {
    @Test func syncEngineAcceptsTheSchema() throws {
        let database = try AppDatabase.openInMemory()
        _ = try AppDatabase.makeSyncEngine(for: database, startImmediately: false)
    }

    @Test func boardsStayARootAndItemsHangOffThem() throws {
        let database = try AppDatabase.openInMemory()
        try database.read { db throws in
            #expect(try db.foreignKeys(on: "boards").isEmpty)
            #expect(try db.foreignKeys(on: "items").map(\.destinationTable) == ["boards"])
            #expect(try db.foreignKeys(on: "reflectionBlocks").map(\.destinationTable) == ["items"])
            #expect(try db.foreignKeys(on: "annotations").map(\.destinationTable) == ["items"])
            #expect(try db.foreignKeys(on: "itemThumbnails").map(\.destinationTable) == ["items"])
            #expect(try db.foreignKeys(on: "tags").isEmpty)
        }
    }

    @Test func deleteRulesMatchTheOldModel() throws {
        let database = try AppDatabase.openInMemory()
        let boardID = UUID()
        let itemID = UUID()
        let targetID = UUID()
        let conversationID = UUID()
        try database.write { db throws in
            try DB.Board.insert { DB.Board(id: boardID, title: "Board") }.execute(db)
            try DB.Item.insert { DB.Item(id: itemID, title: "Item", boardID: boardID) }.execute(db)
            try DB.Item.insert { DB.Item(id: targetID, title: "Target") }.execute(db)
            try DB.Conversation.insert { DB.Conversation(id: conversationID, title: "Chat", boardID: boardID) }.execute(db)
            try DB.ChatMessage.insert { DB.ChatMessage(id: UUID(), conversationID: conversationID) }.execute(db)
            try DB.ReflectionBlock.insert { DB.ReflectionBlock(id: UUID(), itemID: itemID, conversationID: conversationID) }.execute(db)
            try DB.Connection.insert { DB.Connection(id: UUID(), sourceItemID: itemID, targetItemID: targetID) }.execute(db)
            try DB.Nudge.insert { DB.Nudge(id: UUID(), targetItemID: itemID) }.execute(db)
            try DB.ItemThumbnail.insert { DB.ItemThumbnail(itemID: itemID, imageData: Data([1])) }.execute(db)
            try DB.ExtraBoardLink.insert { DB.ExtraBoardLink(itemID: itemID, boardID: UUID()) }.execute(db)

            // A deleted board leaves its items and chats behind, unlinked.
            try DB.Board.find(boardID).delete().execute(db)
            #expect(try DB.Item.find(itemID).fetchOne(db)?.boardID == nil)
            #expect(try DB.Conversation.find(conversationID).fetchOne(db)?.boardID == nil)

            // A deleted conversation takes its messages, and its reflections survive.
            try DB.Conversation.find(conversationID).delete().execute(db)
            #expect(try DB.ChatMessage.all.fetchCount(db) == 0)
            #expect(try DB.ReflectionBlock.all.fetchOne(db)?.conversationID == nil)

            // A deleted item takes everything that hangs off it.
            try DB.Item.find(itemID).delete().execute(db)
            #expect(try DB.ReflectionBlock.all.fetchCount(db) == 0)
            #expect(try DB.Connection.all.fetchCount(db) == 0)
            #expect(try DB.Nudge.all.fetchCount(db) == 0)
            #expect(try DB.ItemThumbnail.all.fetchCount(db) == 0)
            #expect(try DB.ExtraBoardLink.all.fetchCount(db) == 0)
            #expect(try DB.Item.find(targetID).fetchOne(db) != nil)
        }
    }

    @Test func deletingAParentTagClearsItsChildren() throws {
        let database = try AppDatabase.openInMemory()
        let parentID = UUID()
        let childID = UUID()
        try database.write { db throws in
            try DB.Tag.insert { DB.Tag(id: parentID, name: "parent") }.execute(db)
            try DB.Tag.insert { DB.Tag(id: childID, name: "child", parentTagID: parentID) }.execute(db)
            try DB.Tag.find(parentID).delete().execute(db)
            #expect(try DB.Tag.find(childID).fetchOne(db)?.parentTagID == nil)
        }
    }

    @Test func draftsGetAGeneratedID() throws {
        let database = try AppDatabase.openInMemory()
        try database.write { db throws in
            try DB.Item.insert { DB.Item.Draft(title: "No ID given") }.execute(db)
            #expect(try DB.Item.all.fetchOne(db)?.title == "No ID given")
        }
    }
}
